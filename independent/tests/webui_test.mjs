import assert from 'node:assert/strict';
import {bind,shell,validPackage} from '../module/webroot/app.mjs';
assert.equal(validPackage('com.example.game'),true);
for(const invalid of ['com.x;id','com.x\n','',"com.x'",'com.x'.repeat(30),'com.1bad'])assert.equal(validPackage(invalid),false);
const mock=()=>Object.fromEntries(['package','save','off','status'].map(key=>[key,{value:'',textContent:'',disabled:false,events:{},addEventListener(name,fn){this.events[name]=fn;}}]));
const nodes=mock(),commands=[];
await bind({getElementById:id=>nodes[id]},async command=>{commands.push(command);return 'com.old.game';});
assert.equal(nodes.package.value,'com.old.game');
nodes.package.value='com.new.game';await nodes.save.events.click();
assert.equal(commands.at(-1),"setprop persist.pxojdumper.package 'com.new.game'");
const before=commands.length;nodes.package.value='x;id';await nodes.save.events.click();assert.equal(commands.length,before);
await nodes.off.events.click();assert.equal(commands.at(-1),"setprop persist.pxojdumper.package ''");
assert.equal(nodes.save.disabled,false);
const unavailable=mock();await bind({getElementById:id=>unavailable[id]},async()=>{throw Error('no bridge');});
assert.equal(unavailable.save.disabled,true);assert.equal(unavailable.status.textContent,'no bridge');
const failed=mock();let reads=0;
await bind({getElementById:id=>failed[id]},async()=>{if(reads++)throw Error('write failed');return 'com.old.game';});
failed.package.value='com.new.game';await failed.save.events.click();assert.equal(failed.save.disabled,false);assert.equal(failed.status.textContent,'write failed');
const host={ksu:{exec(command,options,key){assert.equal(options,'{}');host[key](0,'com.ok.game\n','');}}};
assert.equal(await shell('getprop persist.pxojdumper.package',host),'com.ok.game');
assert.equal(Object.keys(host).length,1);
await assert.rejects(shell('anything',{}));
const throwing={ksu:{exec(){throw Error('bridge failed');}}};await assert.rejects(shell('anything',throwing));assert.equal(Object.keys(throwing).length,1);
console.log('UI tests passed: validation, load/save/off, missing bridge, save failure, bridge callback cleanup.');
